function sdRows(rows){
  return rows.map(function(r){
    return "<tr><td>"+r[0]+"</td><td>"+r[1]+"</td><td>"+r[2]+"</td><td>"+r[3]+"</td></tr>";
  }).join("");
}
function sdList(arr){
  return arr.map(function(x){ return "<li>"+x+"</li>"; }).join("");
}
